#!/usr/bin/env python3
"""Generate native .strings and offline preview translations from Localization/en.json."""
from argparse import ArgumentParser
from pathlib import Path
import json
import re

parser = ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail if generated resources are out of date')
options = parser.parse_args()
root = Path(__file__).resolve().parent.parent
translations = json.loads((root / 'Localization/en.json').read_text())
for key, value in translations.items():
    if not key or not isinstance(value, str) or not value:
        raise SystemExit(f'Empty localization: {key!r}')
    if sorted(re.findall(r'\{\d+\}', key)) != sorted(re.findall(r'\{\d+\}', value)):
        raise SystemExit(f'Interpolation mismatch: {key!r}')

def quoted(value):
    return json.dumps(value, ensure_ascii=False)

outputs = {}
for language in ['zh-Hans', 'en']:
    body = '// Generated by scripts/generate-localizations.py.\n'
    body += '\n'.join(f'{quoted(key)} = {quoted(key if language == "zh-Hans" else value)};' for key, value in sorted(translations.items())) + '\n'
    outputs[root / f'Sources/ReaderCore/Resources/{language}.lproj/Localizable.strings'] = body

js = '''/* Generated by scripts/generate-localizations.py. */
(() => {
  'use strict';
  let language = 'zh-Hans';
  const english = __ENGLISH__;
  window.lumaUI = {
    get language() { return language; },
    setLanguage(value) { language = value === 'en' ? 'en' : 'zh-Hans'; },
    text(key, ...values) {
      const template = language === 'en' ? english[key] ?? key : key;
      return template.replace(/\\{(\\d+)\\}/g, (token, index) => index < values.length ? String(values[index]) : token);
    }
  };
})();
'''.replace('__ENGLISH__', json.dumps(translations, ensure_ascii=False, sort_keys=True))
outputs[root / 'Sources/Luma/Resources/Markdown/localization.js'] = js
stale = []
for path, content in outputs.items():
    if options.check:
        if not path.exists() or path.read_text() != content:
            stale.append(str(path.relative_to(root)))
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
if stale:
    raise SystemExit('Run python3 scripts/generate-localizations.py:\n' + '\n'.join(stale))
print(f'{"Checked" if options.check else "Generated"} {len(translations)} translations for native UI and offline previews.')
